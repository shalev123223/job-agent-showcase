/**
 * Hostnames refused by name, before DNS is even consulted.
 *
 * `metadata.google.internal` and `metadata.goog` are the GCP metadata service;
 * the AWS/Azure equivalent is an IP literal and is caught by the range check.
 */
const BLOCKED_HOSTNAMES = new Set([
  "localhost",
  "metadata",
  "metadata.google.internal",
  "metadata.goog",
  "instance-data",
]);

const BLOCKED_HOST_SUFFIXES = [".local", ".internal", ".localhost", ".home.arpa"];

/**
 * True for an address nothing on the public internet should be answering on.
 *
 * Covers IPv4 private/loopback/link-local/CGNAT/broadcast/multicast/reserved and
 * the IPv6 equivalents, including IPv4-mapped IPv6 (`::ffff:127.0.0.1`), which
 * is the form that slips past a naive IPv4-only check.
 */
export function isBlockedAddress(address: string): boolean {
  const value = address
    .trim()
    .toLowerCase()
    .replace(/^\[|\]$/g, "");

  // IPv4-mapped IPv6 — unwrap and judge as IPv4.
  const mapped = /^::ffff:(\d+\.\d+\.\d+\.\d+)$/.exec(value);
  if (mapped) return isBlockedAddress(mapped[1] as string);

  if (/^\d+\.\d+\.\d+\.\d+$/.test(value)) {
    const parts = value.split(".").map((p) => Number.parseInt(p, 10));
    if (parts.length !== 4 || parts.some((p) => !Number.isInteger(p) || p < 0 || p > 255)) {
      return true; // Malformed: refuse rather than guess.
    }
    const [a, b] = parts as [number, number, number, number];
    if (a === 0) return true; // "this network"
    if (a === 10) return true; // private
    if (a === 127) return true; // loopback
    if (a === 169 && b === 254) return true; // link-local, incl. 169.254.169.254
    if (a === 172 && b >= 16 && b <= 31) return true; // private
    if (a === 192 && b === 168) return true; // private
    if (a === 100 && b >= 64 && b <= 127) return true; // CGNAT
    if (a === 192 && b === 0) return true; // IETF protocol assignments
    if (a >= 224) return true; // multicast + reserved + broadcast
    return false;
  }

  if (value.includes(":")) {
    if (value === "::" || value === "::1") return true; // unspecified, loopback
    if (value.startsWith("fe80")) return true; // link-local
    if (/^f[cd]/.test(value)) return true; // unique local
    if (value.startsWith("ff")) return true; // multicast
    return false;
  }

  // Not an IP literal at all.
  return false;
}

function isBlockedHostname(hostname: string): boolean {
  const host = hostname.toLowerCase();
  if (BLOCKED_HOSTNAMES.has(host)) return true;
  if (BLOCKED_HOST_SUFFIXES.some((suffix) => host.endsWith(suffix))) return true;
  return isBlockedAddress(host);
}

/**
 * Every per-hop check in one place, so a redirect target is judged by exactly
 * the same rules as the original URL. Splitting these would be how a bypass
 * eventually appears.
 */
async function vetUrl(
  candidate: URL,
  allowedHost: string,
  resolveHost: ResolveHost | undefined,
): Promise<CompanySiteRefusal | null> {
  if (candidate.protocol !== "https:" && candidate.protocol !== "http:") {
    return {
      reason: "blocked_scheme",
      message: `Refused ${candidate.protocol}//… — only http and https are fetched.`,
    };
  }

  const host = candidate.hostname.toLowerCase();

  if (host !== allowedHost.toLowerCase()) {
    return {
      reason: "blocked_host",
      message: `Refused ${host} — this company is pinned to ${allowedHost}, and nothing else is fetched for it.`,
    };
  }

  if (isBlockedHostname(host)) {
    return {
      reason: "blocked_address",
      message: `Refused ${host} — it names a loopback, private or link-local address.`,
    };
  }

  if (resolveHost) {
    let addresses: string[];
    try {
      addresses = await resolveHost(host);
    } catch {
      return { reason: "network_error", message: `Could not resolve ${host}.` };
    }
    const blocked = addresses.find(isBlockedAddress);
    if (blocked) {
      return {
        reason: "blocked_address",
        message: `Refused ${host} — it resolves to ${blocked}, which is not a public address.`,
      };
    }
  }

  return null;
}

/**
 * Resolves what the model asked for against the company's own careers URL.
 *
 * A relative path is joined to the row's URL. An absolute URL is accepted only
 * so the model can pass back a link it read off the listing page verbatim — and
 * it still has to survive `vetUrl`, so an absolute URL pointing anywhere else is
 * refused exactly like any other foreign host.
 */
export function resolveTargetUrl(target: CompanySiteTarget, pathOrUrl?: string): URL | null {
  try {
    if (!pathOrUrl || pathOrUrl.trim() === "") return new URL(target.careersUrl);
    return new URL(pathOrUrl, target.careersUrl);
  } catch {
    return null;
  }
}

