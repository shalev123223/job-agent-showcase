/**
 * Company-direct fetching (ADR-025). The ONLY code in this project that fetches
 * an arbitrary company web page, and the only place the rules below are
 * enforced.
 *
 * THE SAFETY PROPERTY, STATED ONCE: this connector refuses any host but the one
 * on the `job_target_companies` row it was given. Not "prefers"; refuses. The
 * host comes from `careers_host`, which Postgres GENERATED from `careers_url` at
 * write time — so the check reads a stored value rather than re-deriving one
 * from a string a caller passed in, and a caller cannot widen it by parsing
 * differently.
 *
 * THE MODEL NEVER SUPPLIES A HOST. `fetch_company_page` and
 * `fetch_company_jobs` take a `company_id` and a PATH. The origin is looked up
 * from the database row. There is deliberately no tool anywhere in this project
 * that accepts a URL from the model and fetches it — that is the difference
 * between this connector and the `web_fetch` ADR-025 rejected.
 *
 * WHY NOT APIFY. Apify covers LinkedIn, and search_jobs already owns it. A
 * company's own careers page is the case Apify does not cover, which is the
 * entire reason `job_target_companies` exists as the LITERAL counterpart to
 * `job_search_directions`'s semantic intent.
 *
 * WHAT AN UNTRUSTED URL CAN STILL NOT REACH. Shalev types these URLs, and typed
 * input is untrusted input, so every one of these is enforced per request and
 * per redirect hop:
 *
 *   - scheme must be http or https (no file:, no gopher:, no data:)
 *   - host must equal the row's careers_host exactly, after lowercasing
 *   - literal IP hosts in private, loopback, link-local, CGNAT, multicast or
 *     reserved ranges are refused — this is what stops 169.254.169.254 and
 *     friends, which is the cloud-metadata endpoint every SSRF write-up starts
 *     with
 *   - names that resolve inside the network (localhost, *.local, *.internal,
 *     metadata.google.internal) are refused by name as well
 *   - when a DNS resolver is available, the RESOLVED addresses are checked too,
 *     so a public name pointing at 127.0.0.1 does not get through
 *   - redirects are followed manually, capped, and re-checked in full at every
 *     hop — an allowed host redirecting to an internal one is the classic
 *     bypass, and `redirect: "follow"` would take it silently
 *   - the response is capped in bytes and in wall-clock time, so a hostile or
 *     merely enormous page cannot exhaust the isolate
 *   - only HTML/plain-text content types are read at all
 *
 * PAGE TEXT IS DATA, NEVER INSTRUCTIONS. What comes back here reaches the model
 * as tool output. The system prompt already states that job descriptions are
 * data; the same holds, more so, for a whole page fetched from the open web.
 */

export type CompanySiteTarget = {
  companyId: string;
  companyName: string;
  /** The row's own careers URL — the origin every fetch is resolved against. */
  careersUrl: string;
  /** Generated by Postgres at write time. The allowlist, of exactly one host. */
  careersHost: string;
};

